namespace {

	struct Generated {
		bool ok = false;
		str text;
		Vector<GraphDiagnostic> diagnostics{GetMemoryResource(MemTag::Editor)};

		bool Has(std::string_view fragment) const { return text.find(fragment) != str::npos; }
		bool Names(u32 node, std::string_view fragment) const {
			for (const GraphDiagnostic& diagnostic : diagnostics) {
				if (diagnostic.node == node && diagnostic.message.find(fragment) != str::npos) {
					return true;
				}
			}
			return false;
		}
		str Report() const {
			str out;
			for (const GraphDiagnostic& diagnostic : diagnostics) {
				out += "node " + std::to_string(diagnostic.node) + ": " + diagnostic.message + "\n";
			}
			return out;
		}
	};

	Generated Generate(const GraphDocument& document) {
		Generated out;
		out.ok = GraphSurface::Generate(document, "project://Assets/Test.slshader", out.text, out.diagnostics);
		return out;
	}

	GraphBuilder LitStack() {
		GraphBuilder b;
		GraphContext& fragment = b.Context(1, "Context/Fragment");
		constexpr std::string_view BLOCKS[] = {"Block/BaseColor", "Block/NormalTS", "Block/Metallic", "Block/Roughness",
											   "Block/Reflectance", "Block/Emission", "Block/Occlusion", "Block/Alpha"};
		u32 id = 2;
		for (std::string_view block : BLOCKS) {
			b.Block(fragment, id++, block);
		}
		return b;
	}

} // anonymous namespace

TEST(NodeShaderSurfaceTest, OneDocumentGeneratesOneByteString) {
	GraphBuilder b = LitStack();
	b.Property(20, 30, "tint", "Color");
	b.document.properties.back().defaultValue = "[1,0.5,0.25,1]";
	b.Blackboard(21, "Albedo", "albedo", "Texture2D");
	b.Node(31, "Math/Multiply");
	b.Connect(30, "Out", 31, "A");
	b.Connect(31, "Out", 2, "Value");

	Generated first = Generate(b.document);
	ASSERT_TRUE(first.ok) << first.Report();
	Generated again = Generate(b.document);
	EXPECT_EQ(first.text, again.text);

	GraphDocument reread;
	str error;
	ASSERT_TRUE(GraphDocumentOps::Read(GraphDocumentOps::Write(b.document), reread, error)) << error;
	EXPECT_EQ(Generate(reread).text, first.text);

	EXPECT_TRUE(first.Has("// generated by Node Shader from project://Assets/Test.slshader")) << first.text;
	EXPECT_TRUE(first.Has("#pragma shalltear_template lit\n"));
	EXPECT_TRUE(first.Has("void ShalltearSurfaceFunction(ShalltearSurfaceInput input, inout ShalltearSurface surface) {"));
}

TEST(NodeShaderSurfaceTest, EachPropertyDeclaresMemberAndPragmas) {
	GraphBuilder b = LitStack();
	b.Blackboard(20, "Strength", "strength", "Float", "0.5");
	GraphProperty& slider = b.Blackboard(21, "Gloss", "gloss", "Float", "0.25");
	slider.settings.push_back({str("max"), str("2")});
	slider.settings.push_back({str("min"), str("-1")});
	slider.settings.push_back({str("mode"), str("\"slider\"")});
	b.Blackboard(22, "Steps", "steps", "Float", "3.7").settings.push_back({str("mode"), str("\"integer\"")});
	b.Blackboard(23, "Use Rim", "useRim", "Boolean", "true");
	b.Blackboard(24, "Offset", "offset", "Vector2", "[1,-2]");
	b.Blackboard(25, "Tint", "tint", "Color", "[1,0.5,0.25,1]");
	b.Blackboard(26, "Glow", "glow", "Color", "[4,2,1,1]").settings.push_back({str("mode"), str("\"hdr\"")});
	GraphProperty& secret = b.Blackboard(27, "Secret", "secret", "Color", "[0,0,0,1]");
	secret.settings.push_back({str("hidden"), str("true")});
	b.Blackboard(28, "Bump", "bump", "Texture2D").settings.push_back({str("mode"), str("\"normal\"")});
	b.document.properties[2].settings.push_back({str("group"), str("\"Surface Inputs\"")});
	b.document.properties[5].settings.push_back({str("group"), str("\"Surface Inputs\"")});

	Generated g = Generate(b.document);
	ASSERT_TRUE(g.ok) << g.Report();

	EXPECT_TRUE(g.Has("[[vk::binding(0, 1)]] cbuffer ShalltearMaterial {\n\tfloat strength;\n\tfloat gloss;\n\tint steps;\n\tint useRim;\n"
					  "\tfloat2 offset;\n\tfloat4 tint;\n\tfloat4 glow;\n\tfloat4 secret;\n};"))
		<< g.text;
	EXPECT_TRUE(g.Has("[[vk::binding(1, 1)]] Texture2D bump;\n[[vk::binding(2, 1)]] SamplerState sltSampler_bump;")) << g.text;

	EXPECT_TRUE(g.Has("#pragma shalltear_default strength 0.5\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_range gloss -1 2\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_default steps 3\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_default useRim 1\n#pragma shalltear_hint useRim toggle\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_default offset 1 -2\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_hint tint color\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_hint glow hdr\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_hint secret hidden\n"));
	EXPECT_FALSE(g.Has("#pragma shalltear_hint secret color"));
	EXPECT_TRUE(g.Has("#pragma shalltear_default bump normal\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_label useRim \"Use Rim\"\n"));
	EXPECT_TRUE(g.Has("#pragma shalltear_group \"Surface Inputs\" steps tint\n"));

	EXPECT_TRUE(g.Has("float strength;"));
}

TEST(NodeShaderSurfaceTest, EighthTextureIsRefusedNamingBlackboard) {
	GraphBuilder b = LitStack();
	for (u32 i = 0; i < 7; ++i) {
		b.Blackboard(20 + i, "Map", "map" + std::to_string(i), "Texture2D");
	}
	b.Blackboard(40, "Tint", "tint", "Color");
	Generated seven = Generate(b.document);
	EXPECT_TRUE(seven.ok) << seven.Report();

	b.Blackboard(27, "Map", "map7", "Texture2D");
	Generated eight = Generate(b.document);
	EXPECT_FALSE(eight.ok);
	EXPECT_TRUE(eight.Names(0, "the blackboard declares 8 textures (a material binds at most 7)")) << eight.Report();
}

TEST(NodeShaderSurfaceTest, OnlyTargetsActiveBlocksWriteSurface) {
	GraphBuilder b = LitStack();
	Generated lit = Generate(b.document);
	ASSERT_TRUE(lit.ok) << lit.Report();
	for (std::string_view field : {"baseColor", "alpha", "metallic", "roughness", "reflectance", "normal", "occlusion", "emissive"}) {
		EXPECT_TRUE(lit.Has("\tsurface." + str(field) + " = ")) << field;
	}

	b.Graph("target", "\"unlit\"");
	Generated unlit = Generate(b.document);
	ASSERT_TRUE(unlit.ok) << unlit.Report();
	EXPECT_TRUE(unlit.Has("#pragma shalltear_template unlit\n"));
	EXPECT_TRUE(unlit.Has("\tsurface.baseColor = "));
	EXPECT_TRUE(unlit.Has("\tsurface.alpha = "));
	EXPECT_FALSE(unlit.Has("surface.metallic"));
	EXPECT_FALSE(unlit.Has("surface.normal"));
}

TEST(NodeShaderSurfaceTest, WorldNormalWrittenInTangentFrame) {
	GraphBuilder b = LitStack();
	b.Block(b.document.contexts[0], 20, "Block/NormalWS");
	b.Graph("normalSpace", "\"world\"");
	Generated world = Generate(b.document);
	ASSERT_TRUE(world.ok) << world.Report();
	EXPECT_TRUE(world.Has("float3 ShalltearGraphWorldToTangent(ShalltearSurfaceInput input, float3 normalWS)"));
	EXPECT_TRUE(world.Has("\tsurface.normal = ShalltearGraphWorldToTangent(input, (input.normalWS));")) << world.text;

	size_t first = world.text.find("surface.normal =");
	EXPECT_EQ(world.text.find("surface.normal =", first + 1), str::npos);

	b.document.settings.back().value = "\"object\"";
	Generated object = Generate(b.document);
	EXPECT_FALSE(object.ok);
	EXPECT_TRUE(object.Names(0, "has no object space")) << object.Report();
}

