TEST(NodeShaderSurfaceTest, EveryFieldIntegratorReadsHasBlock) {
	std::filesystem::path surface;
	for (std::filesystem::path probe = std::filesystem::current_path(); !probe.empty(); probe = probe.parent_path()) {
		if (std::filesystem::exists(probe / "EngineAssets" / "Shaders" / "Surface.hlsli")) {
			surface = probe / "EngineAssets" / "Shaders" / "Surface.hlsli";
			break;
		}
		if (probe == probe.parent_path()) {
			break;
		}
	}
	if (surface.empty()) {
		GTEST_SKIP() << "EngineAssets not found";
	}
	str contract = FileSystem::ReadTextFile(Path(surface.generic_string()), MemTag::Editor);
	size_t begin = contract.find("struct ShalltearSurface {");
	size_t end = contract.find("// reserved", begin);
	ASSERT_NE(begin, str::npos);
	ASSERT_NE(end, str::npos);

	Generated lit = Generate(LitStack().document);
	ASSERT_TRUE(lit.ok) << lit.Report();
	u32 fields = 0;
	std::string_view body(contract.data() + begin, end - begin);
	for (size_t line = body.find('\n'); line != std::string_view::npos && line + 1 < body.size(); line = body.find('\n', line + 1)) {
		std::string_view text = body.substr(line + 1, body.find('\n', line + 1) - line - 1);
		size_t type = text.find_first_not_of("\t ");
		if (type == std::string_view::npos || !text.substr(type).starts_with("float")) {
			continue;
		}
		size_t name = text.find(' ', type) + 1;
		std::string_view field = text.substr(name, text.find(';') - name);
		EXPECT_TRUE(lit.Has("\tsurface." + str(field) + " = ")) << "the contract's '" << field;
		++fields;
	}
	EXPECT_EQ(fields, 8u);
}
